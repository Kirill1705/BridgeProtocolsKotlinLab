CREATE TABLE IF NOT EXISTS boards (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    number INTEGER NOT NULL CHECK (number > 0),
    dealer VARCHAR(1) NOT NULL,
    vulnerable VARCHAR(3) NOT NULL CHECK (vulnerable IN ('NS', 'EW', 'ALL', '-'))
);

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    name VARCHAR(30),
    surname VARCHAR(30),
    username VARCHAR(255),
    sport_category NUMERIC(2, 1) CHECK (sport_category >= -5.0 AND sport_category <= 5.0)
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique
    ON users (lower(trim(username))) WHERE username IS NOT NULL AND removed = FALSE;

CREATE TABLE IF NOT EXISTS board_entries (
    id UUID PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT FALSE,
    board_id INTEGER NOT NULL REFERENCES boards(id),
    writer_id UUID NOT NULL REFERENCES users(id),
    contract VARCHAR(6) NOT NULL,
    declarer VARCHAR(1),
    lead VARCHAR(3),
    result INTEGER NOT NULL,
    UNIQUE (board_id, writer_id)
);
